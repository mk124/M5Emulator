void Display::drawText(std::string_view text, int x, int y, int scale, SDL_Color color)
{
	SDL_Renderer* renderer = _renderer.get();
	SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
	for (char character : text)
	{
		const std::size_t index = GlyphCharacters.find(character);
		if (index != std::string_view::npos)
		{
			for (int row = 0; row < GlyphHeight; ++row)
			{
				for (int column = 0; column < GlyphWidth; ++column)
				{
					if (!(Glyphs[index][row] & (1u << (GlyphWidth - 1 - column)))) continue;
					const SDL_Rect dot { x + column * scale, y + row * scale, scale, scale };
					checkSdl(SDL_RenderFillRect(renderer, &dot) == 0, "render control label");
				}
			}
		}
		x += GlyphAdvance * scale;
	}
}

